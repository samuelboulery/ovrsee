/**
 * Récupère une traduction.
 *
 * @param {string} key - Clé de traduction
 * @param {'fr' | 'en'} lang - Langue ('fr' ou 'en')
 * @param {Object<string, string|number>} [params] - Paramètres nommés pour substitution
 * @returns {string} La chaîne traduite avec les paramètres substitués
 */
function t(key, lang, params) {
  // Repli en cascade, jamais d'exception : une clé absente doit donner un texte
  // laid, pas un écran vide. `t()` est appelé pendant le rendu, et une
  // exception y emporte l'onglet entier — c'est le défaut que le garde-fou de
  // rendu a déjà eu à rattraper une fois. Le test de parité des dictionnaires
  // reste le vrai filet ; celui-ci n'est que la ceinture.
  const translated = translations[lang]?.[key] ?? translations.en?.[key] ?? key

  if (!params) return translated

  return translated.replace(/\$\{(\w+)\}/g, (_, paramName) => {
    const value = params[paramName]
    if (value === undefined) {
      throw new Error(`Missing parameter: ${paramName} for key ${key}`)
    }
    return String(value)
  })
}

export { t, translations }
